add_heading(doc, "6. Discussion", level=1)

add_heading(doc, "6.1 Adaptive control advantage", level=2)

add_paragraph(doc,
    "The most important finding of this study is that the "
    "metacognitive arbiter achieves the same total "
    "violation reduction as the best fixed-mode "
    "controller (Fixed System 2) while dynamically "
    "allocating control effort. The total violation "
    "reduction is 37.9% relative to no control, "
    "concentrated in the two generator outage scenarios "
    "(G1 and G2) where the system-wide impact is "
    "largest. The fact that the arbiter does not "
    "outperform Fixed System 2 in the total violation "
    "count reflects a feature of the test scenarios "
    "rather than a limitation of the arbiter: in the "
    "six 39-bus scenarios, the breaches that occur are "
    "predominantly thermal, where System 2 is the "
    "appropriate response. Scenarios in which voltage "
    "or stability margins degrade without a thermal "
    "breach — for example, a voltage stability event "
    "triggered by a heavy reactive load pickup — would "
    "show the arbiter outperforming Fixed System 2, "
    "because Fixed System 2 would not engage System 1 "
    "and would not arrest the voltage decline.")

add_paragraph(doc,
    "The arbiter's advantage is therefore not in the "
    "violation count but in the qualitative nature of the "
    "control response. The arbiter engages the fast "
    "System 1 channel when the dominant breach is "
    "voltage or stability, and the slow System 2 channel "
    "when the dominant breach is thermal, and combines "
    "the two when both are present. The mode timeline in "
    "Figure 2 shows this directly: in scenario G1, the "
    "arbiter engages both System 1 and System 2 within a "
    "few seconds of the outage, with the System 1 effort "
    "reaching full scale faster than the System 2 "
    "effort. A fixed-mode controller cannot replicate "
    "this behavior because it does not have the "
    "metacognitive layer that decides which channel to "
    "engage. In a control room, the practical advantage "
    "of the arbiter is that the operator sees a single, "
    "consistent control response that adapts to the "
    "current risk, rather than having to manually select "
    "between fast and slow corrective actions.")

add_heading(doc, "6.2 Nomogram interpretability", level=2)

add_paragraph(doc,
    "The extracted nomogram in Figure 4 is the operator-"
    "facing artifact that makes the arbiter policy "
    "interpretable. The nomogram is a 2D heatmap with "
    "clear axes (load level and pre-outage margin) and a "
    "small, discrete set of cell labels (0, 1, 2, 3) "
    "corresponding to the arbiter modes. An operator can "
    "look up the current operating point and read off "
    "the recommended control mode in seconds, which is "
    "comparable to the use of a traditional nomogram. "
    "The nomogram is also consistent with the real-time "
    "controller because both are produced by the same "
    "policy: if the operator follows the nomogram "
    "recommendation, the resulting control action is "
    "the same action the arbiter would take if it were "
    "in automatic mode. This consistency is a deliberate "
    "design property of the framework and addresses the "
    "long-standing tension in IRO-017-1 outage "
    "coordination between offline nomograms and "
    "real-time operation.")

add_paragraph(doc,
    "The interpretability of the nomogram depends on the "
    "dimensionality of the operating point. In this "
    "paper we use a 2D grid (load level × pre-outage "
    "margin) for clarity. In a production tool the "
    "nomogram would typically have additional dimensions "
    "(e.g., generation pattern, renewable forecast, "
    "weather proxy), which would require either a "
    "higher-dimensional visualization or a set of 2D "
    "slices at fixed values of the additional variables. "
    "The 2D slice approach is the standard way of "
    "presenting multi-dimensional nomograms in "
    "operational practice and would not require any "
    "change to the arbiter policy; only the nomogram "
    "extraction procedure would need to be extended.")

add_heading(doc, "6.3 Limitations", level=2)

add_paragraph(doc,
    "Several limitations of the present study should be "
    "noted. First, the System 1 and System 2 control "
    "actions are proxies for the actual fast and slow "
    "corrective resources that an operator would "
    "dispatch. System 1 is modeled as a coordinated AVR "
    "setpoint bump rather than as explicit FACTS "
    "devices or EV V2G, because in the IEEE 39-bus "
    "system the shunt injection alone has a small effect "
    "on bus voltages (the slack generator absorbs most "
    "of the local reactive injection). System 2 is "
    "modeled as greedy corrective load shedding rather "
    "than as a full OPF, because the proxy is "
    "sufficient to demonstrate the arbiter's decision-"
    "making and the OPF would add a substantial "
    "computational cost. A production tool would "
    "replace both proxies with the actual controllable "
    "resources.")

add_paragraph(doc,
    "Second, the time-domain simulation is quasi-static "
    "and does not model transient stability. The arbiter "
    "is therefore evaluated on the slower "
    "electromechanical and operational timescale of "
    "seconds to minutes; transient events on the "
    "sub-second timescale (e.g., the first few cycles "
    "after a fault) are not captured. Extending the "
    "framework to transient stability would require a "
    "dynamic simulation with generator dynamics, "
    "exciter models, and governor models, which is "
    "beyond the scope of this paper but is a natural "
    "next step. Third, the IEEE 39-bus scenarios are "
    "calibrated to demonstrate post-outage SOL breaches; "
    "the absolute violation counts and reduction "
    "percentages should not be generalized to a real "
    "system without re-calibration. Fourth, the IEEE "
    "118-bus check is a single line outage and not a "
    "full outage catalog; a full 118-bus outage catalog "
    "would be needed to evaluate the scalability of the "
    "violation reduction claims.")

add_heading(doc, "6.4 Real-time deployment considerations", level=2)

add_paragraph(doc,
    "Real-time deployment of the arbiter in a control "
    "room would require several additional components "
    "beyond the simulation described in this paper. "
    "First, a state estimator would provide the "
    "real-time network state (bus voltages, branch "
    "flows) at the cadence required by the arbiter (we "
    "use a 2 s time step in the simulation, which is "
    "compatible with a typical state estimator cycle). "
    "Second, a contingency screening tool would "
    "provide the pre-outage SOL margins that the "
    "arbiter uses as inputs; in our simulation these "
    "are computed directly from the power-flow solution, "
    "but in a real-time deployment they would typically "
    "come from a real-time contingency analysis (RTCA) "
    "tool. Third, the corrective actions recommended by "
    "the arbiter would need to be communicated to the "
    "operator or to the automated dispatch system; the "
    "nomogram in Figure 4 is one form of this "
    "communication, and the real-time mode strip in "
    "Figure 2 is another.")

add_paragraph(doc,
    "The computational cost of the arbiter itself is "
    "modest: the decision function in Listing 2 is a "
    "small set of comparisons and runs in microseconds. "
    "The computational cost is dominated by the SOL "
    "margin computation, which requires one or more "
    "power-flow solutions. In our simulation we use "
    "pypower's Newton-Raphson solver, which solves the "
    "39-bus system in well under a second on a laptop-"
    "class CPU. In a real-time deployment the solver "
    "would typically be a production-grade tool "
    "(e.g., a commercial state estimator or RTCA), and "
    "the arbiter would consume the margin values "
    "directly rather than computing them. The arbiter "
    "is therefore a thin layer on top of existing "
    "real-time tools, which is a desirable property for "
    "deployment: the arbiter does not require replacing "
    "the existing real-time tool stack.")

