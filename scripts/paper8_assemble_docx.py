add_heading(doc, "3.1 EV V2G model: reactive support and active curtailment",
            level=2)
add_paragraph(doc,
    "We model an EV fleet at a transmission bus as a controllable negative "
    "load whose active and reactive injections are computed from the local "
    "voltage magnitude through a piecewise-linear droop law. Each EV is "
    "assumed to provide up to 3.3 kVAR of reactive capability and 6.6 kW "
    "of active curtailment capability (i.e., a 6.6 kW charger at 0.95 "
    "power factor with bidirectional inverter control). For a fleet of "
    "n EVs at bus b, the maximum reactive injection is therefore "
    "Q_max,b = n × 3.3 × 10⁻³ MVAr and the maximum active curtailment is "
    "P_max,b = n × 6.6 × 10⁻³ MW. The V2G command is governed by a "
    "voltage-deviation signal V_err = V_ref − V_pu, with V_ref = 0.95 pu, "
    "and is realized through a first-order lag with response time τ.")

add_code_block(doc, '''def ev_v2g_command(V_pu, n_evs, modes=('Q','P'), ev_tau=0.3,
                   dt=0.2, prev=None):
    """V2G P (curtailment, MW) and Q (injection, MVAr) for one timestep."""
    if prev is None:
        prev = EVFleetState()
    Q_max_MVAR = n_evs * EV_Q_PER_EV_KVAR / 1e3   # 3.3 kVAR/EV
    P_max_MW   = n_evs * EV_P_PER_EV_KW   / 1e3   # 6.6 kW/EV
    V_err = EV_V_REF - V_pu                          # 0.95 pu reference
    if V_err <= 0 or n_evs == 0:
        Q_target, P_target = 0.0, 0.0
    else:
        Q_target = (min(EV_K_Q * V_err * Q_max_MVAR, Q_max_MVAR)
                    if 'Q' in modes else 0.0)
        P_target = (min(EV_K_P * V_err * P_max_MW,   P_max_MW)
                    if 'P' in modes else 0.0)
    alpha = dt / (ev_tau + dt)                       # first-order lag
    P_state = prev.P + alpha * (P_target - prev.P)
    Q_state = prev.Q + alpha * (Q_target - prev.Q)
    return P_state, Q_state, EVFleetState(P_state, Q_state)''')

add_paragraph(doc,
    "The droop gains K_Q = 4.0 and K_P = 1.5 are chosen so that the V2G "
    "command saturates at its capability bound when the local voltage "
    "deviation reaches approximately 0.25 pu (for Q) and 0.67 pu (for P), "
    "respectively; in practice, both saturate at voltages far below the "
    "UVLS Stage 1 threshold of 0.90 pu, which is the operating region we "
    "target. The response time τ is treated as a tuning parameter, swept "
    "in the sensitivity analysis between 0.1 s (sub-cycle inverter "
    "response) and 5.0 s (representative of slower communications-"
    "controlled aggregation). The two operating modes 'Q+P', 'Q-only', and "
    "'P-only' allow us to isolate the contribution of reactive support "
    "versus active curtailment to UVLS deferral.")

add_heading(doc, "3.2 UVLS staged relay logic", level=2)
add_paragraph(doc,
    "Each load bus is equipped with an independent UVLS relay implementing "
    "four stages. Each stage is defined by a voltage threshold V_th (pu), "
    "a time delay T_d (s), and a shed fraction f_s (per unit of local load). "
    "When the local voltage magnitude drops below V_th, the stage's timer "
    "accumulates; when the timer reaches T_d, the stage trips and the "
    "corresponding fraction of load is shed. Voltage recovery above V_th "
    "resets the stage's timer (a non-accumulative implementation, which is "
    "the more conservative and more common implementation in NPCC "
    "Directory 1 practice). Once a stage has tripped, it cannot re-trip in "
    "the same event. The stage settings used here, listed in Table 1, are "
    "representative of NPCC practice and align with IEEE C37.117.")

add_code_block(doc, '''UVLS_STAGES = [
    # (name, V_threshold_pu, time_delay_s, pct_load_shed)
    ("S1", 0.90, 10.0, 0.07),
    ("S2", 0.85,  3.0, 0.10),
    ("S3", 0.80,  1.0, 0.15),
    ("S4", 0.75,  0.5, 0.20),
]

class UVLSRelay:
    def __init__(self):
        self.timers  = [0.0] * len(UVLS_STAGES)
        self.fired   = [False] * len(UVLS_STAGES)
        self.shed_MW = 0.0

    def update(self, V_pu, dt, orig_load_MW):
        actions = []
        for i, (name, V_th, T_d, pct) in enumerate(UVLS_STAGES):
            if self.fired[i]:
                continue
            if V_pu < V_th:
                self.timers[i] += dt
                if self.timers[i] >= T_d:
                    shed = pct * orig_load_MW
                    self.shed_MW += shed
                    self.fired[i] = True
                    actions.append((name, shed))
            else:
                self.timers[i] = 0.0  # reset on recovery
        return actions''')

add_heading(doc, "3.3 Loading-margin bisection for voltage stability", level=2)
add_paragraph(doc,
    "The voltage stability loading margin is computed by bisecting the "
    "load-scaling factor λ between a lower bound at which the power flow "
    "converges and an upper bound at which it does not. The bisection "
    "narrows the bracket until its width is below a tolerance (here "
    "0.005 pu on λ). The margin in MW is then (λ_max − 1) × P_load,base, "
    "where P_load,base is the total active load of the base case. We "
    "implement the bisection both as a custom while-loop and via "
    "scipy.optimize.bisect applied to a sign-flipped convergence indicator, "
    "and confirm that both implementations return the same λ_max within "
    "tolerance. The custom implementation is preferred in the main loop "
    "because it is more robust to the occasional non-monotonic behavior "
    "of the Newton-Raphson convergence flag near the nose of the PV curve.")

add_code_block(doc, '''def loading_margin_lambda(ppc, ev_fleet=None,
                                ev_modes=('Q','P'),
                                max_lambda=2.5, tol=0.005):
    """Bisect to find the largest load scale at which PF still converges."""
    if pf_converges_at_lambda(ppc, max_lambda, ev_fleet, ev_modes):
        return max_lambda
    if not pf_converges_at_lambda(ppc, 1.0, ev_fleet, ev_modes):
        return 1.0
    lo, hi = 1.0, max_lambda
    # Expand the upper bracket first
    while pf_converges_at_lambda(ppc, hi, ev_fleet, ev_modes) and hi - lo > 1e-3:
        lo = hi
        hi = min(hi * 1.5, max_lambda)
    # Then bisect the bracket
    while hi - lo > tol:
        mid = 0.5 * (lo + hi)
        if pf_converges_at_lambda(ppc, mid, ev_fleet, ev_modes):
            lo = mid
        else:
            hi = mid
    return lo

def loading_margin_MW(ppc, ev_fleet=None, ev_modes=('Q','P'),
                      max_lambda=2.5, tol=0.005):
    lam = loading_margin_lambda(ppc, ev_fleet, ev_modes, max_lambda, tol)
    return lam, (lam - 1.0) * ppc['bus'][:, 2].sum()''')

add_heading(doc, "3.4 Coordination control law and severe contingency", level=2)
add_paragraph(doc,
    "The coordination control law is implicit in the simulation loop: at "
    "each timestep, the EV V2G command is computed from the previous "
    "timestep's voltage, the resulting injection reduces the net load at "
    "the EV bus, the power flow is re-solved, and the UVLS relay is "
    "advanced against the new voltage. The V2G response is therefore a "
    "fast-acting corrective action that operates on a sub-second to "
    "second timescale, while the UVLS relay operates on a 1–10 s timescale, "
    "giving V2G the first opportunity to arrest voltage decline before "
    "UVLS arms. The severe contingency is constructed as a double event: "
    "at t = 2.0 s, branch 24 (the 15–16 line) is tripped, and simultaneously "
    "a load ramp begins that scales all loads linearly from 1.0 to 1.20 "
    "over an 8 s window, after which the load is held at 1.20. This "
    "contingency pushes the voltage at bus 15 (a 320 MW load center) to "
    "approximately 0.81 pu, sufficient to arm UVLS Stages 1 and 2 in the "
    "baseline (no-V2G) case.")

add_heading(doc, "3.5 Quasi-static time-domain simulation algorithm", level=2)
add_paragraph(doc,
    "The quasi-static time-domain simulation interleaves power-flow "
    "solves with discrete-event UVLS relay updates. Each timestep "
    "comprises four operations: (i) the line trip is applied (if scheduled "
    "and not already executed); (ii) the load-ramp factor is evaluated at "
    "the current simulation time and the loads are scaled accordingly; "
    "(iii) the EV V2G P and Q commands are computed from the previous "
    "timestep's local voltage using the first-order droop law, and the "
    "net bus loads are reduced by the V2G injection; (iv) the Newton–"
    "Raphson power flow is re-solved, the new bus voltages are recorded, "
    "and the per-bus UVLS relay is advanced against the new voltage. "
    "Conservative handling is used when the power flow fails to converge: "
    "the voltages are held at the previous timestep's values and the "
    "UVLS relay is not advanced, on the rationale that a non-converging "
    "power flow indicates that the system is at or past the nose of the "
    "PV curve and UVLS arming is no longer the dominant phenomenon.")

add_paragraph(doc,
    "The simulation uses a timestep of dt = 0.2 s and a total horizon of "
    "30 s. With 151 timesteps per scenario, and approximately 0.04 s per "
    "Newton-Raphson power flow on the IEEE 39-bus system, each scenario "
    "takes roughly 6 s on a laptop-class CPU. The full sweep over 6 fleet "
    "sizes × 3 modes, plus the 25-point sensitivity sweep, completes in "
    "approximately 90 s. The simulation is fully deterministic: the "
    "power-flow initial guess is taken from the previous timestep's "
    "solution (warm start), and the UVLS relay timers and EV V2G state "
    "are carried forward explicitly between timesteps. We deliberately "
    "do not apply generator Pmax enforcement on the slack bus during the "
    "time-domain simulation, which would otherwise prevent the slack "
    "from picking up the load-ramp imbalance; this is the standard "
    "treatment in seconds-to-minutes emergency studies where the slack "
    "represents the aggregate of AGC-controlled units and the unit "
    "commitment is fixed.")

add_heading(doc, "3.6 Computation of UVLS reduction metrics", level=2)
add_paragraph(doc,
    "Two scalar metrics summarize each scenario. The first is the total "
    "UVLS MW shed, which is the sum of shed_MW across all stages and all "
    "load buses at the end of the 30 s simulation horizon. The second is "
    "the UVLS MW reduction, defined as the difference between the baseline "
    "(no-V2G) total shed and the scenario's total shed. We also report "
    "the number of distinct UVLS trip events as a tertiary metric, "
    "which captures the spread of UVLS arming across buses and stages. "
    "For the voltage stability loading margin, we report λ_max (the "
    "load-scaling factor at the nose of the PV curve) and the loading "
    "margin in MW, (λ_max − 1) × P_load,base. The margin gain attributable "
    "to V2G is the difference between the scenario's loading margin and "
    "the baseline (no-V2G) loading margin.")

