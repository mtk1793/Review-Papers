def add_paragraph(doc: Document, text: str, italic: bool = False,
                 size: int = 11, align: WD_ALIGN_PARAGRAPH = WD_ALIGN_PARAGRAPH.JUSTIFY) -> None:
    p = doc.add_paragraph()
