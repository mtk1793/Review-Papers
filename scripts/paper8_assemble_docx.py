add_heading(doc, "6. Discussion", level=1)

add_paragraph(doc,
    "The results in Section 5 support three headline findings. First, "
    "coordinated V2G can reduce UVLS MW shed by 64–79 % in the severe "
    "contingency we constructed, with combined Q+P V2G at 50,000–75,000 "
    "EVs eliminating UVLS Stage 2 entirely and leaving only a single "
    "Stage 1 event. Second, reactive power injection is the dominant "
    "contribution: Q-only V2G achieves most of the benefit of Q+P V2G at "
    "large fleet sizes, while P-only V2G achieves only half the benefit "
    "even at 100,000 EVs. This is consistent with the underlying physics "
    "of voltage stability, which is governed primarily by reactive power "
    "balance in the network. Third, fleet size dominates response time "
    "in determining UVLS reduction, but at intermediate fleet sizes the "
    "response time interacts with the staged UVLS thresholds in non-"
    "monotonic ways that should be considered when tuning V2G "
    "deployments.")

add_paragraph(doc,
    "From a standards perspective, the results support the inclusion of "
    "fast-acting distributed resources in the UVLS coordination analysis "
    "that PRC-010-2 mandates. The standard currently focuses on "
    "coordination with other protection and control equipment, but does "
    "not explicitly enumerate V2G or other distributed energy resources "
    "as candidate coordinated assets. Our results suggest that a "
    "moderate V2G deployment (50,000 EVs, equivalent to 5 % of system "
    "peak load in charger capacity, or roughly 0.5 % of registered EVs "
    "in a region of 10 million EVs) can substantially reduce the UVLS "
    "burden on the system, and could be quantified as a coordination "
    "credit in the UVLS evaluation.")

add_paragraph(doc,
    "Several limitations should be noted. First, the quasi-static time-"
    "domain simulation captures steady-state voltage behavior at each "
    "timestep but does not represent generator dynamics, load "
    "frequency response, or transient stability. For the UVLS "
    "coordination question, the quasi-static approximation is reasonable "
    "because UVLS operates on a 1–10 s timescale, well above the "
    "electromechanical transient timescale. Second, the EV V2G model is "
    "aggregated at the transmission bus and does not represent the "
    "distribution feeder voltage constraints that may limit the effective "
    "V2G capability at the point of common coupling; in practice, the "
    "distribution feeder may be the binding constraint. Third, the EV "
    "participation factor — the share of EVs connected and available "
    "for V2G at a given time — is treated as 100 % in this study, which "
    "is optimistic; realistic participation factors of 30–50 % would "
    "approximately double the required fleet sizes for the same MW "
    "reduction. Fourth, the severe contingency is constructed as a "
    "single line trip plus a load ramp; a multi-contingency N-2 scenario "
    "or a dynamic load recovery model would yield different UVLS arming "
    "patterns.")

add_paragraph(doc,
    "Real-world deployment considerations include the following. The "
    "interconnection of EV charging stations as V2G-capable resources is "
    "addressed in NERC FAC-002-4 (Facilities Design, Connections, and "
    "Maintenance) and in IEEE 1547-2018, which set the technical "
    "requirements for distributed resources interconnected at the "
    "distribution level. Aggregating these resources to provide "
    "transmission-level services requires a communication and control "
    "infrastructure (often referred to as a distributed energy resource "
    "management system, or DERMS) that can issue V2G commands at "
    "sub-second to second cadence — well within current SCADA and "
    "synchrophasor capabilities. The market compensability of V2G as a "
    "voltage-support ancillary service is currently limited in most "
    "regions; the standards and market design would need to evolve to "
    "compensate V2G for the UVLS deferral credit our analysis quantifies.")

